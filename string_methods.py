#python string manipulation examples

#define the original strings
s = "Hello, world!"

#convert the string to uppercase 
print(s.upper())

#convert the string to lowercase
print(s.lower())

#remove leading and trailing whitespaces from the strings
print(s.strip())

#replace all occurance of 'o' with 'x' in the string
print(s.replace('o','x'))

# count the number of occurances of 'a' in the string
print('Abracadabra'.count('a'))